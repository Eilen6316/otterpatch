import { readdir, readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const packageRoot = fileURLToPath(new URL('..', import.meta.url));
const skillsDir = path.join(packageRoot, 'skills');
const outputPath = path.join(packageRoot, 'src', 'playbooks.generated.ts');

const directories = (await readdir(skillsDir, { withFileTypes: true }))
  .filter((entry) => entry.isDirectory())
  .map((entry) => entry.name)
  .sort();

if (!directories.length) throw new Error(`No playbook directories found in ${skillsDir}`);

const manifest = {};
for (const name of directories) {
  const sourcePath = path.join(skillsDir, name, 'SKILL.md');
  const markdown = (await readFile(sourcePath, 'utf8')).replace(/\r\n/g, '\n');
  if (!markdown.trim()) throw new Error(`Empty playbook: ${sourcePath}`);
  manifest[name] = markdown;
}

const generated = [
  '/* This file is generated by scripts/generate-playbooks.mjs. Do not edit directly. */',
  `export const PLAYBOOK_MARKDOWN = ${JSON.stringify(manifest, null, 2)} as const;`,
  '',
].join('\n');

await writeFile(outputPath, generated, 'utf8');
